"""Reference implementation of dp-tower (projects/23-recursion/specs/SRS.md).

The moves are generated by the recursive procedure of SRS-23 FR-07; the input loop is shared
with the project's other tools.
"""

from __future__ import annotations

from ._recursion_stream import run_tool
from .common import Token, out, parse_int_token

TOOL = "dp-tower"
PROMPT_TEXT = "Enter number of disks: "
MAX_DISKS = 20  # 2**20 - 1 moves, 36 700 125 bytes of output
NOTHING = b"There's nothing to move!\n"
HELP_TEXT = """\
Usage: dp-tower [OPTION]... [FILE]
Print the moves that solve the Tower of Hanoi, computed by recursion.

With no FILE, or when FILE is -, read standard input.  For each number of
disks N in FILE (a whole number, at most 20), print the 2^N-1 moves that carry
a tower of N disks from peg A to peg B, using peg C as the spare, one move per
line.  For a number below 1, print "There's nothing to move!".

Options:
  -p, --prompt    write the prompt 'Enter number of disks: ' to standard error
                    before each number is read
      --help      display this help and exit
      --version   output version information and exit
"""


def move_line(origin: str, destination: str) -> bytes:
    return f"Move top disk from peg {origin} to peg {destination}.\n".encode("ascii")


def tower(origin: str, destination: str, spare: str, n: int) -> None:
    """Move n >= 1 disks from origin to destination, using spare."""
    if n == 1:
        out.write(move_line(origin, destination))
        return
    tower(origin, spare, destination, n - 1)
    out.write(move_line(origin, destination))
    tower(spare, destination, origin, n - 1)


def answer(token: Token, source: str) -> None:
    n = parse_int_token(token, source, maximum=MAX_DISKS)
    if n < 1:
        out.write(NOTHING)
    else:
        tower("A", "B", "C", n)


def main(argv: list[str]) -> int:
    return run_tool(argv, TOOL, HELP_TEXT, PROMPT_TEXT, answer)
